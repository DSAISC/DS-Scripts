local function updateAirFloat()
    if not airHumanoid or not airRoot then return end
    local inAir = (airHumanoid:GetState() == Enum.HumanoidStateType.Freefall or airHumanoid:GetState() == Enum.HumanoidStateType.Jumping)
    if airActive and shouldFloat and inAir then
        if not airBV then local bv = Instance.new("BodyVelocity") bv.MaxForce = Vector3.new(math.huge, math.huge, math.huge) bv.Velocity = Vector3.zero bv.Parent = airRoot airBV = bv end
        if not airHBConn then airHBConn = R.Heartbeat:Connect(function() if airBV and airBV.Parent and airHumanoid then local moveDir = airHumanoid.MoveDirection local speed = airHumanoid.WalkSpeed airBV.Velocity = Vector3.new(moveDir.X * speed, 0, moveDir.Z * speed) end end) end
    else if airBV then airBV:Destroy(); airBV = nil end if airHBConn then airHBConn:Disconnect(); airHBConn = nil end end
end
