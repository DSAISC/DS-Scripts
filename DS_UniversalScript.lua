local lh = nil local dws = 16 local hue = 0
R.Heartbeat:Connect(function(dt)
    hue = (hue + 60 * dt) % 360
    local color = Color3.fromHSV(hue / 360, 1, 1)
    mainStroke.Color = color
    if flyStroke then flyStroke.Color = color end
    if airStroke then airStroke.Color = color end
    ti.TextColor3 = color
    local c = p.Character local h = c and c:FindFirstChildOfClass("Humanoid") local r = c and c:FindFirstChild("HumanoidRootPart")
    if h then
        if h ~= lh then dws = h.WalkSpeed; lh = h end
        if s.walkspeed then h.WalkSpeed = math.max(1, s.walkspeedValue) else h.WalkSpeed = dws end
        if s.speedMultiplier then h.WalkSpeed = h.WalkSpeed * s.speedMultiplierValue end
    else lh = nil end
    if s.gravity then workspace.Gravity = 196.2 * s.gravityValue else workspace.Gravity = 196.2 end
    if c and s.noclip then for _, v in ipairs(c:GetDescendants()) do if v:IsA("BasePart") then v.CanCollide = false end end end
    if flyActive and r and h then
        h.PlatformStand = true
        local md = h.MoveDirection if md.Magnitude > 0 then md = md.Unit else md = Vector3.zero end
        local sp = s.flyspeed and s.flyspeedValue or 50
        local mv = md * sp * dt
        if vert == 1 then mv = mv + Vector3.new(0, sp * dt, 0) elseif vert == -1 then mv = mv + Vector3.new(0, -sp * dt, 0) end
        r.CFrame = r.CFrame + mv; r.Velocity = Vector3.zero; r.RotVelocity = Vector3.zero
    end
    if s.esp and s.espLine and r then
        local cam = workspace.CurrentCamera
        if cam then
            local myPos, onScreen = cam:WorldToViewportPoint(r.Position)
            if not onScreen then myPos = nil end
            for _, v in ipairs(game:GetService("Players"):GetPlayers()) do
                if v ~= p and v.Character then
                    local tr = v.Character:FindFirstChild("HumanoidRootPart")
                    if tr then
                        local tpos, vis = cam:WorldToViewportPoint(tr.Position)
                        if vis and myPos then
                            local line = espLines[v]
                            if not line then line = Drawing.new("Line") line.Thickness = 2 line.Color = Color3.fromRGB(255, 0, 0) espLines[v] = line end
                            line.Visible = true line.From = Vector2.new(myPos.X, myPos.Y) line.To = Vector2.new(tpos.X, tpos.Y)
                        elseif espLines[v] then espLines[v]:Remove(); espLines[v] = nil end
                    end
                end
            end
        end
    else for k, line in pairs(espLines) do line:Remove(); espLines[k] = nil end end
end)
